#!/usr/bin/env python3
"""Generate kernel-tier (decide +kernel) files for an upper bound K_q(n,R) <= M using the
K2 machinery (CoveringKernel.go / go_split / cover_simple) and the C1 data list.
Leaves = all prefixes of length D (theorem per leaf), grouped into part files by step budget.
Usage: gen.py CELL q n R M D PART_STEPS steps_file outdir
steps_file: lines 'P<digits> steps len ok' from sim (prefix digits v0 v1 ... in order applied)."""
import sys, os
cell, q, n, R, M, D, PART = sys.argv[1], *map(int, sys.argv[2:8])
steps_file, outdir = sys.argv[8], sys.argv[9]
W = f"CoveringCerts.Data.{cell}"
pre = f"K3_{cell}"
leaves = []
for line in open(steps_file):
    p, s, _, ok = line.split()
    assert ok == "1", line
    leaves.append((p[1:], int(s)))
assert len(leaves) == q ** D
def items(digs):
    e = f"(wordItems {R} {W})"
    for d in digs:
        e = f"(stepAll {q} {d} {e})"
    return e
def nm(digs): return f"{cell}_q{digs}" if digs else f"{cell}_q"
# group into parts in prefix order
parts, cur, cs = [], [], 0
for p, s in sorted(leaves):
    if cur and cs + s > PART:
        parts.append(cur); cur, cs = [], 0
    cur.append(p); cs += s
if cur: parts.append(cur)
hdr = f"""/-!
GENERATED by gen.py (frente 2, 2026-10-01) -- kernel tier, `decide +kernel` only.
cell: {cell}  q={q} n={n} R={R} M={M}; data = `{W}` (C1_Data_{cell}.lean, sha256 in its header).
leaves: all {q}^{D} prefixes of length {D}; each leaf is `go {q} {n-D} (stepAll ... (wordItems {R} W)) = true`.
-/
"""
os.makedirs(outdir, exist_ok=True)
names = []
for k, ps in enumerate(parts, 1):
    mod = f"{pre}_P{k}"
    names.append(mod)
    with open(os.path.join(outdir, mod + ".lean"), "w") as f:
        f.write(f"import CoveringLean.K2_Core\nimport CoveringLean.C1_Data_{cell}\n\n{hdr}\nnamespace CoveringKernel\n\n")
        for p in ps:
            f.write(f"theorem {nm(p)} : go {q} {n-D} {items(p)} = true := by decide +kernel\n\n")
        f.write("end CoveringKernel\n")
# assembly
with open(os.path.join(outdir, pre + ".lean"), "w") as f:
    f.write("import CoveringLean.K2_Core\nimport CoveringLean.C1_CoverCheck\n")
    for m in names: f.write(f"import CoveringLean.{m}\n")
    f.write(f"\n{hdr}\nnamespace CoveringKernel\n\n")
    for depth in range(D - 1, -1, -1):
        import itertools
        for t in itertools.product(range(q), repeat=depth):
            p = "".join(map(str, t))
            f.write(f"theorem {nm(p)} : go {q} {n-depth} {items(p)} = true :=\n")
            f.write(f"  go_split {q} {n-depth-1} {items(p)} (by\n  intro v hv\n  interval_cases v\n")
            for v in range(q):
                f.write(f"  · exact {nm(p+str(v))}\n")
            f.write("  )\n\n")
    f.write(f"""theorem {cell}_le_{M}_kernel_le :
    ∃ C : Finset (Fin {n} → ZMod {q}), C.card ≤ {M} ∧ CoveringA2.Covers {R} C := by
  have h := cover_simple {q} {n} {R} {W} {nm('')}
  have hl : {W}.length = {M} := by decide +kernel
  rw [hl] at h
  exact h

end CoveringKernel

#print axioms CoveringKernel.{cell}_le_{M}_kernel_le
""")
print(len(parts), "parts;", [sum(s for p, s in leaves if p in set(ps)) for ps in parts][:5])
